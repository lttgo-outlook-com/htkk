	public void formatTheoLoaiTien(SheetView sView, HTKKCMCToKhaiInfo ToKhaiInfo, HTKKPeriodInfo PeriodInfo)
	{
		HTKKCMCSheetInfo hTKKCMCSheetInfo = ToKhaiInfo.SheetInfos[0];
		foreach (HTKKCMCCellInfo staticCell in hTKKCMCSheetInfo.StaticCells)
		{
			if (staticCell.CellTemplate.RowIndex >= 61 && staticCell.CellTemplate.RowIndex <= 66)
			{
				GeneralFunctions.InsertNumberCell(sView, staticCell.CellTemplate.RowIndex, staticCell.CellTemplate.ColIndex, staticCell.Value, staticCell.Validate, (PeriodInfo.DonViTinhMa == "USD") ? DEFAULT_LOAI_TIEN_KHAC : "0");
			}
		}
